-- 331: Bonus — wages before the app + saved bonus calculations.
--
-- 1. employee_opening_wages: wages (and optionally presents) an employee
--    earned BEFORE the ERP started (from the old note books). PPK,
--    2026-11-03: for bonus 8/11/25 – 20/5/26 Subramani 73,174, Viji 51,151.
--    The Bonus page adds a row when its period overlaps the bonus From–To.
-- 2. bonus_run: a saved bonus calculation (period, % / ₹ settings and every
--    employee's presents / wages / bonus as shown), so it can be reopened,
--    reprinted and compared with next year.
BEGIN;

CREATE TABLE IF NOT EXISTS public.employee_opening_wages (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id  bigint NOT NULL REFERENCES public.employee(id),
  period_from  date NOT NULL,
  period_to    date NOT NULL,
  amount       numeric(12,2) NOT NULL DEFAULT 0,
  presents     numeric(8,2),
  notes        text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  created_by   uuid REFERENCES public.app_user(id) DEFAULT auth.uid(),
  CONSTRAINT employee_opening_wages_range CHECK (period_to >= period_from),
  CONSTRAINT employee_opening_wages_amount_nonneg CHECK (amount >= 0)
);
CREATE INDEX IF NOT EXISTS idx_employee_opening_wages_emp ON public.employee_opening_wages(employee_id);

CREATE TABLE IF NOT EXISTS public.bonus_run (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        text NOT NULL,
  period_from  date NOT NULL,
  period_to    date NOT NULL,
  settings     jsonb NOT NULL DEFAULT '{}'::jsonb,
  rows         jsonb NOT NULL DEFAULT '[]'::jsonb,
  grand_total  numeric(12,2) NOT NULL DEFAULT 0,
  created_at   timestamptz NOT NULL DEFAULT now(),
  created_by   uuid REFERENCES public.app_user(id) DEFAULT auth.uid(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['employee_opening_wages', 'bonus_run'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_read', t);
    EXECUTE format($p$CREATE POLICY %I ON public.%I FOR SELECT USING (
      EXISTS (SELECT 1 FROM public.app_user u WHERE u.id = auth.uid() AND u.status = 'active'
              AND u.role IN ('owner','accounts','mill_manager','auditor')))$p$, t || '_read', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_write', t);
    EXECUTE format($p$CREATE POLICY %I ON public.%I FOR ALL USING (
      EXISTS (SELECT 1 FROM public.app_user u WHERE u.id = auth.uid() AND u.status = 'active'
              AND u.role IN ('owner','accounts')))
      WITH CHECK (
      EXISTS (SELECT 1 FROM public.app_user u WHERE u.id = auth.uid() AND u.status = 'active'
              AND u.role IN ('owner','accounts')))$p$, t || '_write', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO authenticated, service_role', t);
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE public.%I TO authenticated, service_role', t || '_id_seq');
    EXECUTE format('DROP TRIGGER IF EXISTS trg_zz_dup_guard ON public.%I', t);
    EXECUTE format('CREATE TRIGGER trg_zz_dup_guard BEFORE INSERT ON public.%I FOR EACH ROW EXECUTE FUNCTION public.fn_dup_guard()', t);
  END LOOP;
END $$;

COMMIT;
