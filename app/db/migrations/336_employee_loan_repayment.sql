-- 336: Direct loan repayment — a worker pays a loan back in cash/bank.
--
-- PPK, 2026-11-05: "we need direct loan pay option" on the Loans page.
-- Until now a loan could only be repaid as a deduction on a wage entry.
--
-- employee_loan_repayment: one row per repayment received. dest_ledger_id
-- is the cash/bank account the money went INTO (defaults to CASH), so the
-- cash book shows it as an inflow. Outstanding loan per employee is now
--   SUM(employee_loan.amount) - SUM(wage_entry.loan_deduction)
--                             - SUM(employee_loan_repayment.amount)
BEGIN;

CREATE TABLE IF NOT EXISTS public.employee_loan_repayment (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id    bigint NOT NULL REFERENCES public.employee(id),
  repay_date     date NOT NULL DEFAULT CURRENT_DATE,
  amount         numeric(12,2) NOT NULL CHECK (amount > 0),
  dest_ledger_id bigint REFERENCES public.ledger(id) ON DELETE SET NULL,
  notes          text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  created_by     uuid REFERENCES public.app_user(id) DEFAULT auth.uid(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  updated_by     uuid REFERENCES public.app_user(id)
);
CREATE INDEX IF NOT EXISTS idx_elr_employee ON public.employee_loan_repayment(employee_id);
CREATE INDEX IF NOT EXISTS idx_elr_date ON public.employee_loan_repayment(repay_date);

CREATE OR REPLACE FUNCTION public.fn_loan_repayment_default_dest()
RETURNS trigger LANGUAGE plpgsql AS $f$
DECLARE v_ledger_id bigint;
BEGIN
  IF NEW.dest_ledger_id IS NOT NULL THEN RETURN NEW; END IF;
  SELECT l.id INTO v_ledger_id FROM public.ledger l
    JOIN public.ledger_type lt ON lt.id = l.type_id
   WHERE lt.name = 'CASH' ORDER BY l.id LIMIT 1;
  NEW.dest_ledger_id := v_ledger_id;
  RETURN NEW;
END $f$;
CREATE TRIGGER trg_loan_repayment_default_dest BEFORE INSERT ON public.employee_loan_repayment
  FOR EACH ROW EXECUTE FUNCTION public.fn_loan_repayment_default_dest();
CREATE TRIGGER trg_zz_dup_guard BEFORE INSERT ON public.employee_loan_repayment
  FOR EACH ROW EXECUTE FUNCTION public.fn_dup_guard();

ALTER TABLE public.employee_loan_repayment ENABLE ROW LEVEL SECURITY;
CREATE POLICY employee_loan_repayment_read ON public.employee_loan_repayment FOR SELECT USING (
  EXISTS (SELECT 1 FROM public.app_user u WHERE u.id = auth.uid() AND u.status = 'active'
          AND u.role IN ('owner','accounts','mill_manager','auditor')));
CREATE POLICY employee_loan_repayment_write ON public.employee_loan_repayment FOR ALL USING (
  EXISTS (SELECT 1 FROM public.app_user u WHERE u.id = auth.uid() AND u.status = 'active'
          AND u.role IN ('owner','accounts')))
  WITH CHECK (EXISTS (SELECT 1 FROM public.app_user u WHERE u.id = auth.uid() AND u.status = 'active'
          AND u.role IN ('owner','accounts')));
GRANT SELECT, INSERT, UPDATE, DELETE ON public.employee_loan_repayment TO authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.employee_loan_repayment_id_seq TO authenticated, service_role;

-- Cash book: repayments into CASH are an inflow.
CREATE OR REPLACE FUNCTION public.fn_cash_movements(
  p_from date DEFAULT NULL,
  p_to   date DEFAULT CURRENT_DATE
)
RETURNS TABLE (
  entry_date  date,
  entered_at  timestamptz,
  voucher     text,
  particulars text,
  amount      numeric,   -- signed: + into the drawer, - out of it
  ref_kind    text,
  ref_id      bigint
)
LANGUAGE sql
STABLE
AS $$
  WITH c AS (
    SELECT id FROM public.ledger
     WHERE name = 'CASH'
       AND type_id = (SELECT id FROM public.ledger_type WHERE name = 'CASH')
     LIMIT 1
  ),
  mv AS (
    -- Cash received from or paid to a party
    SELECT p.payment_date, p.created_at, p.payment_no,
           CASE WHEN p.direction = 'in' THEN 'Received — ' ELSE 'Paid — ' END
             || COALESCE(pt.name, 'party'),
           CASE WHEN p.direction = 'in' THEN p.amount ELSE -p.amount END,
           'payment', p.id
      FROM public.payment p
      LEFT JOIN public.party pt ON pt.id = p.party_id
     WHERE p.mode_ledger_id = (SELECT id FROM c)
       AND p.status = 'active'

    UNION ALL
    -- Withdrawn from a bank into the drawer
    SELECT be.entry_date, be.created_at, be.entry_no,
           'Withdrawn from ' || COALESCE(lb.name, 'bank'),
           be.amount, 'bank_entry', be.id
      FROM public.bank_entry be
      LEFT JOIN public.ledger lb ON lb.id = be.bank_ledger_id
     WHERE be.other_ledger_id = (SELECT id FROM c)
       AND be.direction = 'out' AND be.status = 'active'

    UNION ALL
    -- Cash paid out through the bank-entry screen
    SELECT be.entry_date, be.created_at, be.entry_no,
           'Paid — ' || COALESCE(lo.name, 'account'),
           -be.amount, 'bank_entry', be.id
      FROM public.bank_entry be
      LEFT JOIN public.ledger lo ON lo.id = be.other_ledger_id
     WHERE be.bank_ledger_id = (SELECT id FROM c)
       AND be.direction = 'out' AND be.status = 'active'

    UNION ALL
    -- Cash received through the bank-entry screen
    SELECT be.entry_date, be.created_at, be.entry_no,
           'Received — ' || COALESCE(lo.name, 'account'),
           be.amount, 'bank_entry', be.id
      FROM public.bank_entry be
      LEFT JOIN public.ledger lo ON lo.id = be.other_ledger_id
     WHERE be.bank_ledger_id = (SELECT id FROM c)
       AND be.direction = 'in' AND be.status = 'active'

    UNION ALL
    -- Cash paid into a bank
    SELECT be.entry_date, be.created_at, be.entry_no,
           'Deposited to ' || COALESCE(lb.name, 'bank'),
           -be.amount, 'bank_entry', be.id
      FROM public.bank_entry be
      LEFT JOIN public.ledger lb ON lb.id = be.bank_ledger_id
     WHERE be.other_ledger_id = (SELECT id FROM c)
       AND be.direction = 'in' AND be.status = 'active'

    UNION ALL
    -- Wages paid in cash
    SELECT w.pay_date, w.created_at, 'WAGE-' || w.id,
           'Wages — ' || COALESCE(e.full_name, 'employee'),
           -(w.amount - COALESCE(w.loan_deduction, 0)), 'wage_entry', w.id
      FROM public.wage_entry w
      LEFT JOIN public.employee e ON e.id = w.employee_id
     WHERE w.source_ledger_id = (SELECT id FROM c)

    UNION ALL
    -- Expenses paid in cash
    SELECT x.pay_date, x.created_at, 'EXP-' || x.id,
           'Expense — ' || COALESCE(NULLIF(x.category, ''), 'general'),
           -x.amount, 'expense_entry', x.id
      FROM public.expense_entry x
     WHERE x.source_ledger_id = (SELECT id FROM c)

    UNION ALL
    -- Loan repaid directly by the worker (migration 336) — cash comes IN
    SELECT lr.repay_date, lr.created_at, 'LRP-' || lr.id,
           'Loan repaid — ' || COALESCE(e.full_name, 'employee'),
           lr.amount, 'loan_repayment', lr.id
      FROM public.employee_loan_repayment lr
      LEFT JOIN public.employee e ON e.id = lr.employee_id
     WHERE lr.dest_ledger_id = (SELECT id FROM c)
    UNION ALL
    -- Advances given in cash
    SELECT el.loan_date, el.created_at, 'ADV-' || el.id,
           'Advance — ' || COALESCE(e.full_name, 'employee'),
           -el.amount, 'employee_loan', el.id
      FROM public.employee_loan el
      LEFT JOIN public.employee e ON e.id = el.employee_id
     WHERE el.source_ledger_id = (SELECT id FROM c)
  )
  SELECT * FROM mv AS m(entry_date, entered_at, voucher, particulars, amount, ref_kind, ref_id)
   WHERE (p_from IS NULL OR m.entry_date >= p_from)
     AND m.entry_date <= p_to
   ORDER BY m.entry_date, m.entered_at, m.voucher;
$$;

COMMIT;
