-- 317: Bobbin transfer — move IN-STOCK bobbins between in-house stock,
-- outsource weavers and job-work parties (any direction). Stock is derived
-- in metres; the app (lib/bobbin-transfer.ts) writes a stock_ledger OUT at
-- the source and a jobwork_bobbin_issue (party) or opening_stock (in-house)
-- inflow at the destination, and records their ids here for undo.
CREATE TABLE IF NOT EXISTS public.bobbin_transfer (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code               text UNIQUE,
  transfer_date      date NOT NULL DEFAULT CURRENT_DATE,
  from_kind          text NOT NULL CHECK (from_kind IN ('in_house','outsource','jobwork')),
  from_party_id      bigint,
  to_kind            text NOT NULL CHECK (to_kind IN ('in_house','outsource','jobwork')),
  to_party_id        bigint,
  bobbin_id          bigint NOT NULL,
  to_bobbin_id       bigint NOT NULL,
  pieces             numeric(12,2) NOT NULL CHECK (pieces > 0),
  metre_per_pc       numeric(12,2),
  metres             numeric(14,2) NOT NULL,
  vehicle_no         text,
  notes              text,
  ledger_row_id      bigint,
  created_issue_id   bigint,
  created_opening_id bigint,
  created_at         timestamptz NOT NULL DEFAULT now(),
  created_by         uuid DEFAULT auth.uid(),
  CONSTRAINT bobbin_transfer_from_party_chk CHECK ((from_kind = 'in_house') = (from_party_id IS NULL)),
  CONSTRAINT bobbin_transfer_to_party_chk   CHECK ((to_kind = 'in_house') = (to_party_id IS NULL))
);
ALTER TABLE public.bobbin_transfer ENABLE ROW LEVEL SECURITY;
CREATE POLICY p_bobbin_transfer_select ON public.bobbin_transfer FOR SELECT USING (true);
CREATE POLICY p_bobbin_transfer_write ON public.bobbin_transfer FOR ALL
  USING (current_user_role() = ANY (ARRAY['owner'::user_role, 'mill_manager'::user_role]))
  WITH CHECK (current_user_role() = ANY (ARRAY['owner'::user_role, 'mill_manager'::user_role]));
CREATE OR REPLACE FUNCTION public.tg_bobbin_transfer_code() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.code IS NULL OR NEW.code = '' THEN NEW.code := 'BBT-' || lpad(NEW.id::text, 4, '0'); END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_bobbin_transfer_code BEFORE INSERT ON public.bobbin_transfer
  FOR EACH ROW EXECUTE FUNCTION public.tg_bobbin_transfer_code();
