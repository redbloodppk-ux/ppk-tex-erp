-- 316: Paavu transfer — move IN-STOCK sized paavu between in-house stock,
-- outsource weavers and job-work parties (any direction). The movement
-- logic lives in the app (lib/pavu-transfer.ts); these tables record each
-- transfer and everything needed to undo it.
CREATE TABLE IF NOT EXISTS public.pavu_transfer (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              text UNIQUE,
  transfer_date     date NOT NULL DEFAULT CURRENT_DATE,
  from_kind         text NOT NULL CHECK (from_kind IN ('in_house','outsource','jobwork')),
  from_party_id     bigint,
  to_kind           text NOT NULL CHECK (to_kind IN ('in_house','outsource','jobwork')),
  to_party_id       bigint,
  fabric_quality_id bigint,
  vehicle_no        text,
  notes             text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  created_by        uuid DEFAULT auth.uid(),
  CONSTRAINT pavu_transfer_from_party_chk CHECK ((from_kind = 'in_house') = (from_party_id IS NULL)),
  CONSTRAINT pavu_transfer_to_party_chk   CHECK ((to_kind = 'in_house') = (to_party_id IS NULL))
);
CREATE TABLE IF NOT EXISTS public.pavu_transfer_item (
  id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transfer_id              bigint NOT NULL,
  pavu_id                  bigint NOT NULL,
  pavu_code                text,
  beam_no                  text,
  ends                     integer,
  metres                   numeric(12,2) NOT NULL,
  prev_mode                text,
  prev_status              text,
  prev_outsource_ledger_id bigint,
  prev_jobwork_ledger_id   bigint,
  source_cuts              jsonb NOT NULL DEFAULT '[]'::jsonb,
  unlinked_wb_id           bigint,
  created_wb_id            bigint,
  ledger_row_id            bigint
);
ALTER TABLE public.pavu_transfer ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pavu_transfer_item ENABLE ROW LEVEL SECURITY;
CREATE POLICY p_pavu_transfer_select ON public.pavu_transfer FOR SELECT USING (true);
CREATE POLICY p_pavu_transfer_write ON public.pavu_transfer FOR ALL
  USING (current_user_role() = ANY (ARRAY['owner'::user_role, 'mill_manager'::user_role]))
  WITH CHECK (current_user_role() = ANY (ARRAY['owner'::user_role, 'mill_manager'::user_role]));
CREATE POLICY p_pavu_transfer_item_select ON public.pavu_transfer_item FOR SELECT USING (true);
CREATE POLICY p_pavu_transfer_item_write ON public.pavu_transfer_item FOR ALL
  USING (current_user_role() = ANY (ARRAY['owner'::user_role, 'mill_manager'::user_role]))
  WITH CHECK (current_user_role() = ANY (ARRAY['owner'::user_role, 'mill_manager'::user_role]));
CREATE OR REPLACE FUNCTION public.tg_pavu_transfer_code() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.code IS NULL OR NEW.code = '' THEN NEW.code := 'PVT-' || lpad(NEW.id::text, 4, '0'); END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_pavu_transfer_code BEFORE INSERT ON public.pavu_transfer
  FOR EACH ROW EXECUTE FUNCTION public.tg_pavu_transfer_code();
