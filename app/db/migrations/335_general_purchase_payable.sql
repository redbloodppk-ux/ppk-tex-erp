-- 335: General purchases can be a PAYABLE (opt-in per bill).
--
-- PPK, 2026-11-05: "SRI VISHNU TEX bill to be adjusted not shown in contra"
-- and "some party they won't give debit note instead they provide fabric bill
-- for the adjustment". A general purchase was register-only, so such a bill
-- could not be set off against what the party owes us.
--
-- track_payment (default false) keeps every existing spares/services bill
-- out of outstanding; tick it on a bill to make it a payable with its own
-- allocation table, exactly like fabric_purchase (payment_fabric_allocation).
ALTER TABLE public.general_purchase ADD COLUMN IF NOT EXISTS track_payment boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.payment_general_purchase_allocation (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id          bigint NOT NULL REFERENCES public.payment(id) ON DELETE CASCADE,
  general_purchase_id bigint NOT NULL REFERENCES public.general_purchase(id) ON DELETE RESTRICT,
  amount              numeric(14,2) NOT NULL CHECK (amount > 0),
  created_at          timestamptz NOT NULL DEFAULT now(),
  created_by          uuid DEFAULT auth.uid()
);
CREATE INDEX IF NOT EXISTS idx_pgpa_payment ON public.payment_general_purchase_allocation(payment_id);
CREATE INDEX IF NOT EXISTS idx_pgpa_gp ON public.payment_general_purchase_allocation(general_purchase_id);
ALTER TABLE public.payment_general_purchase_allocation ENABLE ROW LEVEL SECURITY;
CREATE POLICY p_pgpa_read ON public.payment_general_purchase_allocation FOR SELECT TO authenticated USING (true);
CREATE POLICY p_pgpa_write ON public.payment_general_purchase_allocation FOR ALL TO authenticated USING (true) WITH CHECK (true);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.payment_general_purchase_allocation TO authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.payment_general_purchase_allocation_id_seq TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.fn_pgpa_recalc_paid()
RETURNS trigger LANGUAGE plpgsql AS $function$
DECLARE target_id bigint;
BEGIN
  target_id := COALESCE(NEW.general_purchase_id, OLD.general_purchase_id);
  UPDATE public.general_purchase gp
     SET amount_paid = COALESCE((SELECT SUM(a.amount) FROM public.payment_general_purchase_allocation a
                                  WHERE a.general_purchase_id = gp.id), 0)
   WHERE gp.id = target_id;
  RETURN COALESCE(NEW, OLD);
END;
$function$;
CREATE TRIGGER trg_pgpa_recalc_paid_ins AFTER INSERT ON public.payment_general_purchase_allocation FOR EACH ROW EXECUTE FUNCTION public.fn_pgpa_recalc_paid();
CREATE TRIGGER trg_pgpa_recalc_paid_upd AFTER UPDATE OF amount ON public.payment_general_purchase_allocation FOR EACH ROW EXECUTE FUNCTION public.fn_pgpa_recalc_paid();
CREATE TRIGGER trg_pgpa_recalc_paid_del AFTER DELETE ON public.payment_general_purchase_allocation FOR EACH ROW EXECUTE FUNCTION public.fn_pgpa_recalc_paid();

